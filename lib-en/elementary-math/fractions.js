  keywords: ["fractions", "fractions", "mixed number", "simplifying a fraction", "common denominator", "repeating decimal", "adding fractions", "multiplying fractions"],
  formulas: [
    { label: "Adding and subtracting fractions", tex: "\\frac{a}{b} \\pm \\frac{c}{d} = \\frac{ad \\pm bc}{bd}" },
    { label: "Multiplying and dividing fractions", tex: "\\frac{a}{b} \\cdot \\frac{c}{d} = \\frac{ac}{bd},\\qquad \\frac{a}{b} \\div \\frac{c}{d} = \\frac{ad}{bc}" }
  ],
  inputs: [
    { id: "a", label: "First fraction a", type: "text", default: "3/4", help: "Accepted examples: 3/4, -2 1/3 (mixed number), 5 (integer), 0.75 (decimal)." },
    { id: "op", label: "Operation", type: "select", default: "add", options: [["add", "+ Add"], ["sub", "− Subtract"], ["mul", "× Multiply"], ["div", "÷ Divide"], ["cmp", "Compare"], ["simplify", "Simplify the first fraction only"]] },
    { id: "b", label: "Second fraction b", type: "text", default: "1/6", when: { op: ["add", "sub", "mul", "div", "cmp"] } }
  ],
  example: { values: { a: "3/4", op: "add", b: "1/6" }, expect: ["11/12", "0.91(6)"], note: "Example: 3/4 + 1/6 = 11/12 = 0.91(6)." },
  invalid: { values: { a: "3/0", op: "add", b: "1/6" } },
  related: ["gcd-lcm", "percentage", "ratio-proportion", "significant-figures"]
